const HAR = /[ً-ْٰ]/;
// фатҳа/касра/замма/сукун — на танвин ва на шадда
const INNER = /[َُِْ]/;
const strip = s => s.replace(/[ً-ٰٟؐ-ؚۖ-ۭ]/g, '');
// Ҷумларо калима ба калима иваз мекунад; аломати китобатӣ ва фосила ҳамон ҷо мемонад.
const vocalize = s => s.replace(/[ء-يً-ْٰ]+/g, w => (INNER.test(w) ? w : (T[w] ?? w)));

const rows = await q(`SELECT w.id, w.word, w.example FROM "Word" w
  JOIN "Lesson" l ON w."lessonId"=l.id JOIN "Module" m ON l."moduleId"=m.id
  WHERE m."courseId"='${COURSE}' AND m."isActive" AND l."isActive"     AND w.example IS NOT NULL AND w.example <> ''`);

const problems = [];
const left = new Map();
const updates = [];
for (const r of rows) {
  const next = vocalize(r.example);
  if (strip(next) !== strip(r.example)) { problems.push(`«${r.example}» → «${next}»: ҳарфҳо тағйир ёфтанд`); continue; }
  for (const w of next.split(/[\s،.,!?؟:;«»"()]+/).filter(Boolean)) {
    if (/[ء-ي]/.test(w) && !INNER.test(w) && (w.match(/[ء-ي]/g) ?? []).length >= 3) {
      left.set(w, (left.get(w) ?? 0) + 1);
    }
  }
  if (next !== r.example) updates.push({ id: r.id, next, old: r.example });
}
console.log(`ҷумлаҳои бе ҳаракат: ${rows.length} · тағйир мешавад: ${updates.length}`);
if (left.size) console.log(`\nдар ҷадвал НЕСТ (${left.size}): ${[...left].map(([w, n]) => `${w}(${n})`).join(' ')}`);
if (problems.length) { console.log(`\n${problems.length} мушкил:`); for (const p of problems.slice(0, 10)) console.log(`  • ${p}`); }
else console.log('✓ ҳар ҷумла ҳамон ҳарфҳоро нигоҳ доштааст.');
console.log('\nнамуна:');
for (const u of updates.slice(0, 6)) console.log(`  ${u.old}\n  → ${u.next}`);

if (CHECK) process.exit(problems.length || left.size ? 1 : 0);
if (problems.length) { console.log('\nНавишта НАШУД.'); process.exit(1); }

for (const u of updates) await q(`UPDATE "Word" SET example=$1 WHERE id=$2`, [u.next, u.id]);
await q(`UPDATE "AppSetting" SET "updatedAt"=NOW() WHERE key='content_version'`);
console.log(`\n${updates.length} ҷумла навишта шуд · content_version ламс шуд.`);
