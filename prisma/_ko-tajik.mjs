// Ҳангул → хониши тоҷикӣ (Word.ipaTajik, қоидаҳои алифбо, дарси шиносоӣ).
//
// ЧАРО як функсия: хониш бояд дар ҲАМА ҷо якхела бошад — корти калима,
// қоидаи алифбо ва дарси шиносоӣ набояд ба ҳамдигар зид бошанд. Китоби
// «2001 калима» барои ин нобоэътимод аст (нафасдорро ишора намекунад, ㅎ-ро гоҳ
// «х» менависад, қоидаҳои пайвастшавиро намедонад).
//
// Қоидаҳо — айнан ҳамон 7 қоидаи экрани Алифбо (`_ko-alphabet.mjs`):
//   №1 пайвастшавӣ (음악 → ымак), №2 бинишавӣ (작년 → чангнён, 합니다 → ҳамнида),
//   №3 ㄴ+ㄹ → лл (연락 → ёллак), №4 сахтшавӣ (학교 → ҳаккё), №5 ㅎ нафасдор мекунад
//   (좋다 → чотха, 축하 → чхукха), №6 ㄷ/ㅌ+이 → ҷи/чхи, №7 ду ҳамсадо дар таг.
// Ва қоидаҳои ҳарф: ㄱㄷㅂㅈ дар мобайн ҷарангдор (г д б ҷ), ㅅ пеши ㅣ/й → ш,
// ㄹ: р / л, дар таг 7 садо (к н т л м п нг), ㅇ дар таг ҲАМЕША «нг».
//
// Конвенсия: ㅓ = о, ㅕ = ё, ㅡ = ы, ㅐ = ㅔ = э, нафасдор = чх кх тх пх,
// дукарата = кк тт пп сс чч. Зада нест. Натиҷа бо ҳарфи хурд.
//
//   import { hangulToTajik, selfTest } from './_ko-tajik.mjs'
//   node prisma/_ko-tajik.mjs            # худсанҷиш
//   node prisma/_ko-tajik.mjs 한국어 학교  # табдил

const JL = ['ㄱ','ㄲ','ㄴ','ㄷ','ㄸ','ㄹ','ㅁ','ㅂ','ㅃ','ㅅ','ㅆ','ㅇ','ㅈ','ㅉ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];
const JV = ['ㅏ','ㅐ','ㅑ','ㅒ','ㅓ','ㅔ','ㅕ','ㅖ','ㅗ','ㅘ','ㅙ','ㅚ','ㅛ','ㅜ','ㅝ','ㅞ','ㅟ','ㅠ','ㅡ','ㅢ','ㅣ'];
const JT = ['','ㄱ','ㄲ','ㄳ','ㄴ','ㄵ','ㄶ','ㄷ','ㄹ','ㄺ','ㄻ','ㄼ','ㄽ','ㄾ','ㄿ','ㅀ','ㅁ','ㅂ','ㅄ','ㅅ','ㅆ','ㅇ','ㅈ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];

const K_CLASS = new Set(['ㄱ', 'ㄲ', 'ㅋ']);
const T_CLASS = new Set(['ㄷ', 'ㅅ', 'ㅆ', 'ㅈ', 'ㅊ', 'ㅌ']);
const P_CLASS = new Set(['ㅂ', 'ㅍ']);
const OBSTRUENT = (t) => K_CLASS.has(t) || T_CLASS.has(t) || P_CLASS.has(t);
const SONORANT_OR_NONE = new Set(['', 'ㄴ', 'ㅁ', 'ㄹ', 'ㅇ']);
const Y_OR_I = new Set(['ㅣ', 'ㅑ', 'ㅕ', 'ㅛ', 'ㅠ', 'ㅒ', 'ㅖ', 'ㅟ']);
const TENSE = { 'ㄱ': 'ㄲ', 'ㄷ': 'ㄸ', 'ㅂ': 'ㅃ', 'ㅅ': 'ㅆ', 'ㅈ': 'ㅉ' };
const H_ASPIRATES = { 'ㄱ': 'ㅋ', 'ㄷ': 'ㅌ', 'ㅈ': 'ㅊ' };                 // ㅎ + ㄱ/ㄷ/ㅈ
const ASPIRATE_BEFORE_H = { 'ㄱ': 'ㅋ', 'ㄲ': 'ㅋ', 'ㄷ': 'ㅌ', 'ㅅ': 'ㅌ', 'ㅈ': 'ㅊ', 'ㅊ': 'ㅊ', 'ㅂ': 'ㅍ' };
const SPLIT = { 'ㄳ': ['ㄱ','ㅅ'], 'ㄵ': ['ㄴ','ㅈ'], 'ㄶ': ['ㄴ','ㅎ'], 'ㄺ': ['ㄹ','ㄱ'], 'ㄻ': ['ㄹ','ㅁ'], 'ㄼ': ['ㄹ','ㅂ'],
                'ㄽ': ['ㄹ','ㅅ'], 'ㄾ': ['ㄹ','ㅌ'], 'ㄿ': ['ㄹ','ㅍ'], 'ㅀ': ['ㄹ','ㅎ'], 'ㅄ': ['ㅂ','ㅅ'] };
const SIMPLE = { 'ㄳ': 'ㄱ', 'ㄵ': 'ㄴ', 'ㄶ': 'ㄴ', 'ㄺ': 'ㄱ', 'ㄻ': 'ㅁ', 'ㄼ': 'ㄹ', 'ㄽ': 'ㄹ', 'ㄾ': 'ㄹ', 'ㄿ': 'ㅂ', 'ㅀ': 'ㄹ', 'ㅄ': 'ㅂ' };

const V_MAP = { 'ㅏ': 'а', 'ㅐ': 'э', 'ㅑ': 'я', 'ㅒ': 'йэ', 'ㅓ': 'о', 'ㅔ': 'э', 'ㅕ': 'ё', 'ㅖ': 'йэ', 'ㅗ': 'о',
                'ㅘ': 'ва', 'ㅙ': 'ве', 'ㅚ': 'ве', 'ㅛ': 'ё', 'ㅜ': 'у', 'ㅝ': 'во', 'ㅞ': 'ве', 'ㅟ': 'ви',
                'ㅠ': 'ю', 'ㅡ': 'ы', 'ㅢ': 'ый', 'ㅣ': 'и' };
// Пас аз ш/ч/ҷ «й»-и садонок шунида намешавад: 샤 = ша, 셔 = шо, 져 = чо.
const DE_Y = { 'я': 'а', 'ё': 'о', 'ю': 'у', 'йэ': 'э' };

// Калимаҳое, ки хониши онҳо аз қоидаи умумӣ берун аст (ва дар алифбо ҳамин тавр
// омӯзонида мешаванд): ㅎ-и мобайни 전화 дар гуфтор меафтад; 의-и соҳибӣ = «э».
const OVERRIDES = { '전화': 'чонва', '나의': 'наэ', '전화번호': 'чонвабонҳо' };

// Рақамҳои хитоию кореягӣ (Модули 4). Ду қоидаи худи рақамҳо, ки қоидаҳои умумӣ намедиҳанд:
//   • ㄹ + 십 → «шш» (칠십 [칠씹], 팔십 [팔씹]) — сахтшавӣ пас аз ㄹ дар калимаҳои хитоӣ;
//   • ҳамсадои таг + 육 → ㄴ илова мешавад (십육 [심뉵], 백육 [뱅뉵]).
const NUM_TOKEN = /^[공일이삼사오육칠팔구십백천만]+$/;
function numericTweaks(s, clean) {
  if (!NUM_TOKEN.test(clean)) return s;
  for (let i = 0; i < s.length - 1; i++) {
    const next = s[i + 1];
    if (s[i].t === 'ㄹ' && next.l === 'ㅅ') next.l = 'ㅆ';
    if (s[i].t && s[i].t !== 'ㄹ' && next.l === 'ㅇ' && next.v === 'ㅠ' && next.t === 'ㄱ') next.l = 'ㄴ';
  }
  return s;
}

function decompose(word) {
  return [...word].filter(ch => ch >= '가' && ch <= '힣').map(ch => {
    const c = ch.charCodeAt(0) - 0xAC00;
    return { l: JL[Math.floor(c / 588)], v: JV[Math.floor((c % 588) / 28)], t: JT[c % 28] };
  });
}

function applySoundChanges(s) {
  // №7 — ду ҳамсадо дар таг.
  for (let i = 0; i < s.length; i++) {
    const t = s[i].t, next = s[i + 1];
    if (!SPLIT[t]) continue;
    const [a, b] = SPLIT[t];
    if (next && next.l === 'ㅇ') {
      s[i].t = a;
      if (b !== 'ㅎ') next.l = b;               // дуюмаш мегузарад; ㅎ пеши садонок меафтад
    } else if (next && b === 'ㅎ' && H_ASPIRATES[next.l]) {
      s[i].t = a; next.l = H_ASPIRATES[next.l];  // 않다 → 안타
    } else {
      s[i].t = SIMPLE[t];
    }
  }
  // №5 — ㅎ дар таг.
  for (let i = 0; i < s.length; i++) {
    if (s[i].t !== 'ㅎ') continue;
    const next = s[i + 1];
    if (next && H_ASPIRATES[next.l]) { next.l = H_ASPIRATES[next.l]; s[i].t = ''; }
    else if (next && next.l === 'ㅇ') s[i].t = '';
    else if (next && next.l === 'ㅅ') { next.l = 'ㅆ'; s[i].t = ''; }
    else if (next && next.l === 'ㄴ') s[i].t = 'ㄴ';
    else s[i].t = 'ㄷ';
  }
  // №5 — ҳамсадо + ㅎ → нафасдор.
  for (let i = 0; i < s.length; i++) {
    const next = s[i + 1];
    if (next && next.l === 'ㅎ' && ASPIRATE_BEFORE_H[s[i].t]) {
      next.l = ASPIRATE_BEFORE_H[s[i].t]; s[i].t = '';
    }
  }
  // №1 ва №6 — пайвастшавӣ; ㄷ/ㅌ пеши 이 → ㅈ/ㅊ.
  for (let i = 0; i < s.length; i++) {
    const t = s[i].t, next = s[i + 1];
    if (!t || t === 'ㅇ' || !next || next.l !== 'ㅇ') continue;
    if ((t === 'ㄷ' || t === 'ㅌ') && next.v === 'ㅣ') next.l = t === 'ㄷ' ? 'ㅈ' : 'ㅊ';
    else next.l = t;
    s[i].t = '';
  }
  // №3, №2, №4 — ҳамсадоҳои ду блоки ҳамсоя.
  for (let i = 0; i < s.length - 1; i++) {
    const next = s[i + 1];
    let t = s[i].t;
    if (!t) continue;
    if (t === 'ㄴ' && next.l === 'ㄹ') s[i].t = 'ㄹ';                  // 연락 → 열락
    else if (t === 'ㄹ' && next.l === 'ㄴ') next.l = 'ㄹ';              // 설날 → 설랄
    else if (next.l === 'ㄹ' && (t === 'ㅁ' || t === 'ㅇ' || OBSTRUENT(t))) next.l = 'ㄴ'; // 음료 → 음뇨
    t = s[i].t;
    if (next.l === 'ㄴ' || next.l === 'ㅁ') {
      if (K_CLASS.has(t)) s[i].t = 'ㅇ';
      else if (T_CLASS.has(t)) s[i].t = 'ㄴ';
      else if (P_CLASS.has(t)) s[i].t = 'ㅁ';
    }
    if (OBSTRUENT(s[i].t) && TENSE[next.l]) next.l = TENSE[next.l];
  }
  return s;
}

function onsetOf(q, i, prevT) {
  const medial = i > 0 && SONORANT_OR_NONE.has(prevT);
  switch (q.l) {
    case 'ㅇ': return '';
    case 'ㄱ': return medial ? 'г' : 'к';
    case 'ㄷ': return medial ? 'д' : 'т';
    case 'ㅂ': return medial ? 'б' : 'п';
    case 'ㅈ': return medial ? 'ҷ' : 'ч';
    case 'ㄲ': return 'кк';
    case 'ㄸ': return 'тт';
    case 'ㅃ': return 'пп';
    case 'ㅉ': return 'чч';
    case 'ㅅ': return Y_OR_I.has(q.v) ? 'ш' : 'с';
    case 'ㅆ': return Y_OR_I.has(q.v) ? 'шш' : 'сс';
    case 'ㅊ': return 'чх';
    case 'ㅋ': return 'кх';
    case 'ㅌ': return 'тх';
    case 'ㅍ': return 'пх';
    case 'ㅎ': return 'ҳ';
    case 'ㄴ': return 'н';
    case 'ㅁ': return 'м';
    case 'ㄹ': return prevT === 'ㄹ' ? 'л' : 'р';
  }
  return '';
}

// 의-и СОҲИБӢ дар охири калима [에] гуфта мешавад (표준 발음법 제5항, ҳамин тавр Despina
// мехонад): 알리의 «аллиэ», 선생님의 «сонсэнгнимэ». Исмҳое ки ХУДАШОН бо 의 тамом
// мешаванд — истисно (회의 «ҳвеи»). Модули 3 (의-и соҳибӣ) 2026-09-11.
const UI_NOUNS = new Set(['회의', '주의', '강의', '동의', '의의', '정의', '편의', '민주주의']);

function vowelOf(q, i, onset, particleUi = false) {
  if (q.v === 'ㅢ') {
    if (q.l === 'ㅇ' && i === 0) return 'ый';
    return particleUi ? 'э' : 'и';
  }
  if (q.v === 'ㅖ' || q.v === 'ㅒ') return q.l === 'ㅇ' && i === 0 ? 'йэ' : 'э';
  const v = V_MAP[q.v];
  if (/[шчҷ]х?$/.test(onset) && DE_Y[v]) return DE_Y[v];
  return v;
}

function codaOf(t) {
  if (!t) return '';
  if (K_CLASS.has(t)) return 'к';
  if (T_CLASS.has(t) || t === 'ㅎ') return 'т';
  if (P_CLASS.has(t)) return 'п';
  return { 'ㄴ': 'н', 'ㄹ': 'л', 'ㅁ': 'м', 'ㅇ': 'нг' }[t] ?? '';
}

function wordToTajik(token) {
  const clean = token.replace(/[^가-힣]/g, '');
  if (!clean) return '';
  if (OVERRIDES[clean]) return OVERRIDES[clean];
  const s = applySoundChanges(numericTweaks(decompose(clean), clean));
  const lastUi = s.length > 1 && clean.endsWith('의') && !UI_NOUNS.has(clean);
  const parts = s.map((q, i) => {
    const onset = onsetOf(q, i, i > 0 ? s[i - 1].t : '');
    return { onset, vowel: vowelOf(q, i, onset, lastUi && i === s.length - 1), coda: codaOf(q.t) };
  });
  // Сахтшавӣ: «к» + «кк» → «кк» (학교 = ҳа-ккё, на ҳак-ккё); «к» + «тт» мемонад.
  let out = '';
  parts.forEach((p, i) => {
    let coda = p.coda;
    const next = parts[i + 1];
    if (next && ['к', 'т', 'п'].includes(coda) && next.onset.startsWith(coda + coda)) coda = '';
    out += p.onset + p.vowel + coda;
  });
  return out;
}

/** Матни ҳангулро (як калима ё ибора) ба хониши тоҷикӣ табдил медиҳад. */
export function hangulToTajik(text) {
  return text.split(/\s+/).map(wordToTajik).filter(Boolean).join(' ');
}

