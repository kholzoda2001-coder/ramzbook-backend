export function selfTest() {
  const bad = SELF_TEST.filter(([ko, tj]) => hangulToTajik(ko) !== tj.toLowerCase());
  if (bad.length) {
    throw new Error('Транслитератор: ' + bad.map(([ko, tj]) => `${ko} → «${hangulToTajik(ko)}», интизор «${tj}»`).join('; '));
  }
  return SELF_TEST.length;
}

