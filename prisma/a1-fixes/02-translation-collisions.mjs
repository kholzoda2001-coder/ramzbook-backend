// 02 — Бархӯрди тарҷумаҳо: як калимаи тоҷикӣ барои ду калимаи англисӣ
//
// ⚠️ ПЕШ АЗ ҲАМА, ЯК ЧИЗИ МУҲИМ.
//
// Нақшаи аслӣ «дар қавсайн тавзеҳ илова кунем» буд. Ин ба ТАНҲОӢ КОР
// НАМЕКУНАД, чунки `ExMatch._base` дар `unit_lesson_screen.dart` маҳз ҳамон
// қавсайнро мепартофт:
//
//     String _base(String s) => s.toLowerCase().replaceAll(RegExp(r'\(.*\)'), '');
//
// Яъне «Пой (соқ)» ва «Пой (кафи по)» аллакай тавзеҳ доштанд ва ба ҳар ҳол
// ҳарду ҷуфтшавӣ сабз мешуд. Реша дар КОД буд, на дар мазмун.
//
// Он ислоҳ аллакай ворид шудааст (муқоиса акнун АНИҚ аст), ва он ба ТАНҲОӢ
// ҳамаи панҷ бархӯрди «дар як дарс»-ро мебандад:
//     M1·Д3 I/My · M3·Д4 Nephew/Niece · M11·Д2 Leg/Foot
//     M1·Д1 Hello/Hi · M1·Д1 Goodbye/Bye  (инҳо муродифи ҲАҚИҚӢ буданд)
//
// Ин скрипт кори ДИГАРро мекунад: он ҷойҳоеро ислоҳ мекунад, ки тарҷумаҳо
// АЙНАН якхелаанд ва ҳеҷ тавзеҳ надоранд — он ҷо ҳатто муқоисаи аниқ кӯмак
// намекунад ва хонанда воқеан фарқро дида наметавонад.
//
// Ҳар сатри ҷадвал дастӣ навишта ва санҷида шудааст. Ҳеҷ қоидаи худкор нест.
//
// Иҷро:  node 02-translation-collisions.mjs           (dry-run)
//        node 02-translation-collisions.mjs --apply
// ─────────────────────────────────────────────────────────────────────────────
import { connect, loadCourse, loc, Changes } from './_lib.mjs';

/**
 * Калид — калимаи АНГЛИСӢ (ҳарфи хурд). Қимат — тарҷумаи нав.
 * `only` — агар калима дар якчанд модул бошад, танҳо ҳамин модулҳо.
 *
 * Ҳар сатр сабаби худро дорад: кадом ҷуфт бархӯрд мекард ва чаро маҳз ҳамин
 * калима иваз мешавад (қоида: калимаи БУНЁДӢ шакли соддаро нигоҳ медорад,
 * дуюмаш мушаххас мешавад).
 */
