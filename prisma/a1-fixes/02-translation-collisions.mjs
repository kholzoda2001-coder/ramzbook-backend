const sql = connect();
const modules = await loadCourse(sql);
const ch = new Changes('02 — Бархӯрди тарҷумаҳо');
const applied = new Set();

for (const mod of modules) {
  for (const L of mod.lessons) {
    for (const w of L.words) {
      const key = w.word.trim().toLowerCase();
      const fix = FIXES.find(
        (f) => f.en === key && (!f.modules || f.modules.includes(mod.order + 1))
      );
      if (!fix) continue;
      applied.add(fix.en);
      ch.add({
        table: 'Word', id: w.id, field: 'translation',
        from: w.translation, to: fix.to,
        where: `${loc(mod, L)} · «${w.word}»  ← ${fix.why}`,
      });
    }
  }
}

ch.print();

const missed = FIXES.filter((f) => !applied.has(f.en));
if (missed.length) {
  console.log(`\n  ⚠️  ${missed.length} сатри ҷадвал ба ягон калима нарасид:`);
  for (const m of missed) console.log(`       • «${m.en}» (модулҳо: ${m.modules?.join(',') ?? 'ҳама'})`);
}

console.log(`
  ЁДОВАРӢ: ислоҳи ЛОГИКӢ аллакай ворид шудааст —
  \`ExMatch._base\` дигар қавсайнро намепартояд, пас «Пой (соқ)» ва
  «Пой (кафи по)» акнун ду ҷавоби ГУНОГУНанд. Ин скрипт танҳо он ҷойҳоро
  ислоҳ мекунад, ки тарҷумаҳо АЙНАН якхела буданд.`);

ch.writeSql(new URL('./out/02-translation-collisions.sql', import.meta.url).pathname.replace(/^\//, ''));
await ch.apply(sql);
