// Табдили УНВОН барои курси русӣ — сарчашмаи ЯГОНА.
//
// Ду скрипт инро тақсим мекунанд (`fix-ru-titles.mjs` ва
// `fix-ru-m1m2-content.mjs`), пас нусхабардорӣ манъ аст: агар қоидаи ҳарфи
// калон дар як ҷо иваз шавад ва дар ҷои дигар не, унвонҳо аз ҳам дур мешаванд.
//
// Санҷиш: `node prisma/fix-ru-titles.mjs --selftest` (21 санҷиш).

// ── Исмҳои хос: ҳеҷ гоҳ ба ҳарфи хурд намераванд ────────────────────────────
// «Душанбе» қасдан ин ҷост: ҳам шаҳр аст, ҳам рӯзи ҳафта — маҳз ҳамон дом, ки
// нормалайзери кӯҳна ба он афтода буд. Дар унвон вай ҳамеша ШАҲР аст.
const PROPER = new Set([
  'душанбе', 'москва', 'россия', 'русия', 'таджикистан', 'тоҷикистон',
  'дубай', 'лондон', 'америка', 'англия', 'оаэ',
  'али', 'алӣ', 'олег', 'рустам', 'лола', 'ҷамол',
  'русӣ', 'тоҷикӣ', 'англисӣ', 'русский', 'таджикский', 'английский',
  // Калимаҳои РУСӢ, ки дар унвони мавзӯъ ҲАМЧУН ИСТИЛОҲ иқтибос мешаванд
  // («Грамматика: Сколько» — мавзӯъ дар бораи ХУДИ ҳамин калима аст). Онҳо
  // истифода намешаванд, балки НОМ бурда мешаванд, пас ҳарфи калон мемонад.
  'сколько', 'этот', 'тот', 'эти', 'те', 'это',
]);

const CYR = /[Ѐ-ӿԀ-ԯ]/;

/**
 * Sentence case барои тоҷикӣ/русӣ — БЕХАТАР.
 * Танҳо ҳарфи КАЛОНи калимаи миёнаро хурд мекунад, ва он ҳам бо чор шарт.
 */
export function sentenceCase(input) {
  const out = [];
  let i = 0;
  let startOfSentence = true;
  let inQuote = false;

  while (i < input.length) {
    const ch = input[i];

    // Матни дохили «…» опак аст — на ҳарфаш иваз мешавад, на ҷумларо мешиканад.
    if (ch === '«') { inQuote = true; out.push(ch); i++; continue; }
    if (ch === '»') { inQuote = false; out.push(ch); i++; continue; }
    if (inQuote) { out.push(ch); i++; continue; }

    if (!CYR.test(ch)) {
      out.push(ch);
      // Танҳо «.», «!», «?» ҷумлаи нав мекушоянд. Дупартоб (:) НЕ — баъди он
      // исми ҷинс бо ҳарфи ХУРД меояд: «Грамматика: феъли «Будан»».
      if ('.!?'.includes(ch)) startOfSentence = true;
      i++;
      continue;
    }

    // Калимаи пурраро мегирем.
    let j = i;
    while (j < input.length && (CYR.test(input[j]) || input[j] === '-')) j++;
    const word = input.slice(i, j);
    out.push(transformWord(word, startOfSentence));
    startOfSentence = false;
    i = j;
  }
  return out.join('');
}

function transformWord(word, startOfSentence) {
  const lower = word.toLowerCase();

  // Калимаи аввали ҷумла даст НАМЕХӮРАД.
  //
  // ⚠️ Пештар ин ҷо `toUpperCase()` буд ва унвонҳоеро вайрон мекард, ки бо
  // нохунак ё матни лотинӣ оғоз меёбанд: дар ««Это» — ин аст» аввалин калимаи
  // берун аз нохунак «ин» аст, пас вай «Ин» мешуд. Ҳамин тавр
  // «There is / There are (ҳаст…)» → «(Ҳаст…)» ва «(чиро? киро?)» → «(чиро? Киро?)».
  //
  // Табдил акнун ТАНҲО хурд мекунад, ҳеҷ гоҳ калон. Дар маълумоти воқеӣ ҳар
  // унвон аллакай бо ҳарфи калон сар мешавад, пас ҳеҷ чиз гум намешавад;
  // баркалонкунӣ баъди буридани префикс дар `stripLessonPrefix` мемонад.
  if (startOfSentence) return word;
  // Исми хос — даст намехӯрад.
  if (PROPER.has(lower)) return word;
  // Ҳарфи ЯКТА (Ғ, Ӯ, А) — ё ҳарфи иқтибосшуда аст, ё ҳарфи аввали ном.
  // Ҳеҷ гоҳ хурд намешавад: «Ҳарфҳои Ғ ва Ӯ».
  if (word.length === 1) return word;
  // ҲАМА-КАЛОН (ОАЭ) ё ҳарфи калон дар мобайн (номи брендӣ) — даст намехӯрад.
  const rest = word.slice(1);
  if (rest !== rest.toLowerCase()) return word;
  // Танҳо ҳолати «Калон + боқӣ хурд» хурд карда мешавад.
  if (word[0] === word[0].toUpperCase() && word[0] !== word[0].toLowerCase()) {
    return word[0].toLowerCase() + rest;
  }
  return word;
}

/** Префикси «Модуль 7: » / «Модули 7: » аз аввали унвон. */
export function stripModulePrefix(s) {
  return s.replace(/^\s*Модул[ьи]\s*\d+\s*:\s*/u, '').trim();
}

/**
 * Префикси «Дарси 7: » (тоҷикӣ) ё «Урок 1: » (русӣ) аз аввали унвони ДАРС.
 *
 * ЧАРО: роҳнамо дарсҳоро ХУДАШ рақамгузорӣ мекунад, пас рақами дохили унвон
 * дубора мешавад — «Дарси 9: Дарси 8: феълҳои бозгашта». Бадтараш, рақамҳои
 * сабтшуда ҶОЙ-ҶОЙ ҒАЛАТанд: M4 ду «Дарси 8» дорад ва рақам ба `order`-и
 * воқеӣ намемонад.
 *
 * ⚠️ Баъди буридан ҳарфи аввал КАЛОН карда мешавад. Ин ҳатмист: гузариши
 * sentence case «Дарси»-ро сарҷумла ҳисоб карда буд, пас калимаи баъдӣ хурд
 * шудааст («Дарси 7: калимаҳои самт»). Бе ин қадам унвон бо ҳарфи хурд сар мешуд.
 */
export function stripLessonPrefix(s) {
  const out = s.replace(/^\s*(?:Дарси|Урок|Занятие)\s*\d+\s*:\s*/u, '').trim();
  if (!out) return s.trim(); // унвон ТАНҲО префикс буд — даст намезанем
  return out[0].toUpperCase() + out.slice(1);
}
