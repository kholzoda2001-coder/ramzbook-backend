// ── Худсанҷӣ: ҳар мисол бояд дар курс бо ҳамин хониш бошад ─────────────────
const stripMarks = s => s.replace(/[ً-ٰٟۖ-ۭـ]/g, '').replace(/\s+/g, ' ').trim();
const words = await q(`SELECT w.word, w."ipaTajik" FROM "Word" w
  JOIN "Lesson" l ON w."lessonId"=l.id JOIN "Module" m ON l."moduleId"=m.id
  WHERE m."courseId"='${COURSE}' AND m."isActive"=true AND w."ipaTajik" IS NOT NULL`);
const byWord = new Map();      // бе аломат → хонишҳо
const exactOf = new Map();     // бе аломат → шакли АЙНАНи курс
for (const w of words) {
  const k = stripMarks(w.word);
  byWord.set(k, [...(byWord.get(k) ?? []), w.ipaTajik.trim().toLowerCase()]);
  if (!exactOf.has(k)) exactOf.set(k, w.word.trim());
}

const problems = [];
let checked = 0;
for (const [cat, title, lines] of RULES) {
  const body = lines.join('\n');
  // Мисол = «<арабӣ> (<хониш>)». Номи худи аломат («ً (ду фатҳа)») мисол нест:
  // мисол бояд калимаи ҳақиқӣ, яъне ҳадди ақал ду ҳарфи АСОСӢ дошта бошад.
  for (const m of body.matchAll(/([؀-ۿ][؀-ۿ\s]*?)\s*\(([^)]+)\)/g)) {
    const word = stripMarks(m[1]);
    if ((word.match(/[ء-ي]/g) ?? []).length < 2) continue;
    // Дар қавс баъзан эзоҳ ҳам ҳаст: «(ҳаза, дар сар)» → танҳо хониш гирифта мешавад.
    const read = m[2].trim().toLowerCase().split(/[,—]/)[0].trim();
    checked++;
    const have = byWord.get(word);
    if (!have) { problems.push(`«${title}»: калимаи «${m[1].trim()}» дар курс НЕСТ`); continue; }
    if (!have.includes(read)) problems.push(`«${title}»: «${m[1].trim()}» → қоида «${read}», курс «${have.join('/')}»`);
    // Имлои айнан: қоида набояд калимаро бе ҳаракат нишон диҳад, агар курс
    // онро бо ҳаракат нависад.
    const exact = exactOf.get(word);
    if (exact && exact !== m[1].trim()) problems.push(`«${title}»: имло «${m[1].trim()}» ≠ имлои курс «${exact}»`);
  }
  // Шакл: сатри дароз ва қоидаи дарозро экран намебарорад.
  for (const l of lines) if (l.length > 110) problems.push(`«${title}»: сатри ${l.length} аломат — дароз`);
  if (lines.length > 6) problems.push(`«${title}»: ${lines.length} сатр — зиёд`);
}

const byCat = RULES.reduce((a, [c]) => ((a[c] = (a[c] ?? 0) + 1), a), {});
console.log(`қоидаҳо: ${RULES.length} ${JSON.stringify(byCat)} · мисолҳои санҷидашуда: ${checked}`);
if (problems.length) {
  console.log(`\n${problems.length} номувофиқӣ:`);
  for (const p of problems) console.log(`  • ${p}`);
} else console.log('✓ ҳар мисол бо хониши ҳамон калима дар курс мувофиқ аст.');

if (CHECK) process.exit(problems.length ? 1 : 0);
if (problems.length) { console.log('\nНавишта НАШУД — аввал номувофиқиро ислоҳ кунед.'); process.exit(1); }

