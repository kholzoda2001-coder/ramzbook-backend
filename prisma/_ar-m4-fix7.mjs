for (const [w, ex, tr] of EX)
  await run(`${w} → «${ex}»`,
    `UPDATE "Word" SET example=$2, "exampleTrans"=$3 WHERE "lessonId"=ANY($1) AND word=$4`, [lids, ex, tr, w]);

// ═══ 2 · A13 · матни имтиҳон рӯзи ХУДРО мегирад ════════════════════════
console.log('\n── A13: матни имтиҳон ──');
const testK = ls.find((x) => x.t === 'Имтиҳони ниҳоӣ')?.k;
const TEST_AR = 'عُمْرِي عِشْرُونَ عَاماً. عِيدُ مِيلَادِي فِي يُونْيُو. '
  + 'أَسْتَيْقِظُ فِي السَّاعَةِ السَّادِسَةِ صَبَاحاً. تَبْدَأُ المَدْرَسَةُ فِي السَّاعَةِ التَّاسِعَةِ. '
  + 'يَوْمَ الاِثْنَيْنِ وَالأَرْبِعَاءِ عِنْدَنَا مُوسِيقَى. يَوْمَ الجُمُعَةِ أَنَا حُرٌّ. '
  + 'أَمْسِ كَانَ الأَحَد. كَانَ يَوْمُ الأَحَدِ سَعِيداً. كُنْتُ فِي البَيْتِ مَعَ أُسْرَتِي.';
const TEST_TG = 'Ман бистсола ҳастам. Зодрӯзи ман дар июн аст. '
  + 'Ман соати шаши субҳ бедор мешавам. Мактаб соати нӯҳ сар мешавад. '
  + 'Рӯзҳои душанбе ва чоршанбе мо мусиқӣ дорем. Рӯзи ҷумъа ман озодам. '
  + 'Дирӯз якшанбе буд. Рӯзи якшанбе хуш буд. Ман дар хона бо оилаам будам.';
await run('матни имтиҳон: соати 6 ва 9 (аз матни хониш фарқ мекунад)',
  `UPDATE "ComprehensionExercise" SET passage=$2, "passageTranslated"=$3 WHERE id=$1`,
  [testK, TEST_AR, TEST_TG]);

// ═══ 3 · ҷои ҷавоби дуруст ═════════════════════════════════════════════
console.log('\n── ҷои ҷавоб 4/11/4 → 6/6/7 ──');
// [унвони дарс, тартиби савол, вариантҳои НАВ, индекси дуруст, шарҳи нав|null]
const Q = [
  ['Вақт ва рақамҳо', 2, ['الثَّامِنَة', 'السَّابِعَة', 'العَاشِرَة'], 0, null],
  ['Вақт ва рақамҳо', 3, ['أَحَدَ عَشَرَ', 'اِثْنَا عَشَرَ', 'ثَلَاثَةَ عَشَرَ'], 1, null],
  ['Шунавоӣ: Вақт ва рақамҳо', 3, ['السَّاعَةُ الثَّالِثَة', 'السَّاعَةُ الخَامِسَة', 'السَّاعَةُ الرَّابِعَة'], 2, null],
  ['Шунавоӣ: Вақт ва рақамҳо', 4, ['يَوْمَ الاِثْنَيْن', 'يَوْمَ السَّبْت', 'يَوْمَ الجُمُعَة'], 2, null],
  ['Такрор', 4, ['فِي دِيسَمْبِر', 'فِي نُوفَمْبِر', 'فِي يَنَايِر'], 0, null],
  ['Имтиҳони ниҳоӣ', 2, ['السَّابِعَة', 'السَّادِسَة', 'التَّاسِعَة'], 2,
    'Соати шаш вақти бедоршавӣ аст; «تَبْدَأُ المَدْرَسَةُ فِي السَّاعَةِ التَّاسِعَةِ» — мактаб соати нӯҳ.'],
  ['Имтиҳони ниҳоӣ', 6, ['الخَمِيس', 'الأَرْبِعَاء', 'الثُّلَاثَاء'], 1, null],
  ['Имтиҳони ниҳоӣ', 8, ['الجُمُعَة', 'الأَحَد', 'الاِثْنَيْن'], 0, null],
];
for (const [t, ord, opts, ci, ex] of Q) {
  const k = ls.find((x) => x.t === t)?.k;
  await run(`${t} #${ord} → ✓«${opts[ci]}»`,
    ex ? `UPDATE "ComprehensionQuestion" SET options=$2::jsonb, "correctIndex"=$3, explanation=$5 WHERE "exerciseId"=$1 AND "order"=$4`
       : `UPDATE "ComprehensionQuestion" SET options=$2::jsonb, "correctIndex"=$3 WHERE "exerciseId"=$1 AND "order"=$4`,
    ex ? [k, JSON.stringify(opts), ci, ord, ex] : [k, JSON.stringify(opts), ci, ord]);
}
console.log('\nтамом.');
