// IPA-и олмонӣ → хониши тоҷикӣ.
//
// Ҳар ҷое ки `Word.ipaTajik`, `OnboardingWord.transcriptionTajik` ё мисоли
// қоидаи алифбо навишта мешавад, ҳамин як функсия истифода мешавад — вагарна
// хонанда дар қоида як хел ва дар корти калима хели дигар мебинад.
//
// Услуб:  «:» = садоноки дароз,  «́» = зада,  «й» ҳамеша /j/ (то «ю» ва «ё»
// танҳо Ü ва Ö бошанд — ҳамин ду садо барои хонандаи тоҷик навтаринанд),
// «хь» = ç, ŋ пеш аз ҳамсадо «н» (danke → да́нкэ), дар охир «нг» (Wohnung → во́:нунг).

const ACUTE = '́';
const NONSYL = '̯';
const VOWEL = 'аэиоуюё';

// Тартиб МУҲИМ аст: аввал сатрҳои дароз, баъд кӯтоҳ.
const MAP = [
  // дифтонгҳо (аломати ̯ пеш аз ин ҳазф шудааст)
  ['aɪ', 'ай'], ['aʊ', 'ау'], ['ɔʏ', 'ой'], ['ɔɪ', 'ой'],
  ['eɪ', 'эй'], ['oʊ', 'оу'],
  ['ɐ', 'а'],                  // r-и садонокшуда: Bier /biːɐ̯/ → би:а
  // аффрикатҳо
  ['t͡s', 'ц'], ['ts', 'ц'], ['t͡ʃ', 'ч'], ['tʃ', 'ч'],
  ['p͡f', 'пф'], ['pf', 'пф'], ['d͡ʒ', 'ҷ'], ['dʒ', 'ҷ'],
  // садонокҳои дароз
  ['aː', 'а:'], ['ɛː', 'э:'], ['eː', 'э:'], ['iː', 'и:'], ['oː', 'о:'],
  ['uː', 'у:'], ['yː', 'ю:'], ['øː', 'ё:'], ['ɔː', 'о:'], ['œː', 'ё:'],
  // садонокҳои кӯтоҳ
  ['a', 'а'], ['ɑ', 'а'], ['ɛ', 'э'], ['e', 'э'], ['ɪ', 'и'], ['i', 'и'],
  ['ɔ', 'о'], ['o', 'о'], ['ʊ', 'у'], ['u', 'у'], ['ʏ', 'ю'], ['y', 'ю'],
  ['œ', 'ё'], ['ø', 'ё'], ['ə', 'э'],
  // ҳамсадоҳо — ŋ пеш аз ҳамсадо «г»-и барзиёд намедиҳад
  ['ŋk', 'нк'], ['ŋɡ', 'нг'], ['ŋg', 'нг'], ['ŋʒ', 'нж'], ['ŋʃ', 'нш'],
  ['ŋs', 'нс'], ['ŋt', 'нт'], ['ŋ', 'нг'],
  ['ç', 'хь'], ['ʃ', 'ш'], ['ʒ', 'ж'], ['ʁ', 'р'], ['ɡ', 'г'],
  ['p', 'п'], ['b', 'б'], ['t', 'т'], ['d', 'д'], ['k', 'к'], ['g', 'г'],
  ['f', 'ф'], ['v', 'в'], ['s', 'с'], ['z', 'з'], ['x', 'х'], ['h', 'ҳ'],
  ['m', 'м'], ['n', 'н'], ['l', 'л'], ['r', 'р'], ['j', 'й'],
  // сарфи назар
  ['ˌ', ''], ['ʔ', ''], ['̃', ''], ['͡', ''], ['.', ''],
  [' ', ' '], ['-', '-'],
];

/** Хонишро танҳо ҳарфи тоҷикӣ ва аломатҳои иҷозатдодашуда ташкил медиҳад.
 *  «ь» ҳарфи тоҷикӣ нест, вале мо онро қасдан барои садои нарми ç («хь»)
 *  истифода мебарем — ҳамон тавре ки дар қоидаҳои алифбо шарҳ дода шуд. */
export const ALLOWED = /^[абвгдеёжзийклмнопрстуфхцчшъьэюяғқўҳҷӣӯ:́ \-]+$/i;

export function ipaToTajik(ipaRaw) {
  const s = String(ipaRaw).trim().replace(/^\/|\/$/g, '').replace(/^\[|\]$/g, '')
    // ̯ танҳо мегӯяд, ки садонок ҷузъи дифтонг аст — дар хатти тоҷикӣ ифода
    // намеёбад. Ҳазфи он ҷадвалро ду баробар кӯтоҳ мекунад.
    .replace(new RegExp(NONSYL, 'g'), '');
  let out = '';
  let stressPending = false;
  let i = 0;
  while (i < s.length) {
    if (s[i] === 'ˈ') { stressPending = true; i++; continue; }
    const hit = MAP.find(([from]) => s.startsWith(from, i));
    if (!hit) throw new Error(`аломати ношинос «${s[i]}» (U+${s.codePointAt(i).toString(16).toUpperCase()}) дар ${ipaRaw}`);
    let [from, to] = hit;
    if (stressPending && to) {
      // Зада ба ПАСИ аввалин ҳарфи садонок мешинад: «а́:», на «:а́».
      const vi = [...to].findIndex(ch => VOWEL.includes(ch));
      if (vi >= 0) {
        to = to.slice(0, vi + 1) + ACUTE + to.slice(vi + 1);
        stressPending = false;
      }
    }
    out += to;
    i += from.length;
  }
  const res = out.trim();
  if (!ALLOWED.test(res)) throw new Error(`натиҷаи шубҳанок «${res}» аз ${ipaRaw}`);
  return res;
}

/** Худсанҷиш — ҳангоми ба скрипт ворид шудан иҷро мешавад. */
export function selfTest() {
  const cases = [
    ['/ˈhalo/', 'ҳа́ло'], ['/ˈdaŋkə/', 'да́нкэ'], ['/ˈfaːtɐ/', 'фа́:та'],
    ['/naɪn/', 'найн'], ['/dɔʏtʃ/', 'дойч'], ['/ˈʃuːlə/', 'шу́:лэ'],
    ['/ɪç/', 'ихь'], ['/buːx/', 'бу:х'], ['/tsaɪt/', 'цайт'], ['/fʏnf/', 'фюнф'],
    ['/ˈzɪŋən/', 'зи́нгэн'], ['/ɔˈʁaŋʒə/', 'ора́нжэ'], ['/ˈvoːnʊŋ/', 'во́:нунг'],
    ['/jʊŋ/', 'йунг'], ['/tyːp/', 'тю:п'], ['/oˈkeɪ̯/', 'окэ́й'], ['/biːɐ̯/', 'би:а'],
  ];
  const bad = cases.filter(([ipa, want]) => ipaToTajik(ipa) !== want);
  for (const [ipa, want] of bad) console.log(`  ⚠ ${ipa}: гирифтем «${ipaToTajik(ipa)}», интизор «${want}»`);
  if (bad.length) throw new Error(`транслитератор ${bad.length} худсанҷишро нагузаронд`);
  return cases.length;
}
