// ── Сохтани матн ─────────────────────────────────────────────────────────────
const fmtEx = ([ko, tj, mean]) => mean ? `${ko} (${tj} — ${mean})` : `${ko} (${tj})`;
const lineText = (ln) => typeof ln === 'string' ? ln : `${ln.cond} → ${ln.snd}:  ${ln.ex.map(fmtEx).join(', ')}`;
const bodyOf = (r) => r.lines.map(lineText).join('\n');

// ── Санҷишҳо ─────────────────────────────────────────────────────────────────
const P = [];
// 1. Ягонагӣ (машқи toSound).
for (const col of [0, 1, 3]) {
  const vals = LETTERS.map(l => l[col]);
  const dup = vals.filter((v, i) => vals.indexOf(v) !== i);
  if (dup.length) P.push(`такрор дар сутуни ${col}: ${dup.join(', ')}`);
}
// 2. Ҳар ҳарф дар қоидаҳои категорияи худ шарҳ дода шудааст.
for (const [up, , , , cat] of LETTERS) {
  const covered = RULES.some(r => r.cat === cat && r.lines.some(ln => typeof ln === 'object' && ln.x === up));
  if (!covered) P.push(`ҳарфи ${up} (${cat}) дар ягон қоида шарҳ дода нашудааст`);
}
// 3. Ҳар мисол ҳарфро дар ҳамон ҷое дорад, ки сатр мегӯяд.
const allPairs = [];
for (const r of RULES) for (const ln of r.lines) {
  if (typeof ln === 'string') {
    // Ҷуфтҳои «ҳангул (хониш)» дар матни озод ҳам санҷида мешаванд.
    for (const m of ln.matchAll(/([가-힣]+) \(([^)—]+?)(?: — [^)]*)?\)/g)) allPairs.push([m[1], m[2].trim(), r.title]);
    continue;
  }
  if (!POS[ln.pos]) { P.push(`${r.title}: pos-и номаълум «${ln.pos}»`); continue; }
  for (const e of ln.ex) {
    allPairs.push([e[0], e[1], r.title]);
    if (!POS[ln.pos](syl(e[0]), ln.x)) P.push(`${r.title}: ${e[0]} ба шарти «${ln.pos}»${ln.x ? ` (ҳарфи ${ln.x})` : ''} рост намеояд`);
    if (EXPECT[ln.pos] && !EXPECT[ln.pos].test(e[1].toLowerCase())) P.push(`${r.title}: хониши «${e[1]}» (${e[0]}) натиҷаи қоидаро нишон намедиҳад`);
  }
}
// 4. Хониш: танҳо кириллии тоҷикӣ; ㅎ-и сар → «ҳ»; нафасдор → «чх/кх/тх/пх»; ягонагӣ.
const ASP = { 'ㅊ': 'чх', 'ㅋ': 'кх', 'ㅌ': 'тх', 'ㅍ': 'пх' };
const seenReading = new Map();
for (const [ko, tj, where] of allPairs) {
  const low = tj.toLowerCase();
  if (!/^[а-яёғӣқӯҳҷ-]+$/i.test(tj)) P.push(`${where}: хониши «${tj}» (${ko}) аломати бегона дорад`);
  const s = syl(ko);
  if (s[0]?.l === 'ㅎ' && !low.startsWith('ҳ')) P.push(`${where}: ${ko} бо ㅎ сар мешавад, хониш «${tj}» бояд бо «ҳ» сар шавад`);
  for (const q of s) if (ASP[q.l] && !low.includes(ASP[q.l])) P.push(`${where}: ${ko} ${q.l} дорад, хониш «${tj}» бе «${ASP[q.l]}»`);
  if (seenReading.has(ko) && seenReading.get(ko) !== low) P.push(`${ko} ду хониш дорад: «${seenReading.get(ko)}» ва «${low}»`);
  seenReading.set(ko, low);
}
// 5. Шакл: сатр ≤ 110 аломат, қоида ≤ 7 сатр (корти барнома дар телефон).
