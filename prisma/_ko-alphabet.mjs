const [ko] = await sql.query(`SELECT id FROM "Language" WHERE code = 'ko'`);
const [tg] = await sql.query(`SELECT id FROM "Language" WHERE code = 'tg'`);
if (!ko || !tg) {
  console.error('✗ ko ё tg ёфт нашуд — аввал _ko-add-http.mjs-ро иҷро кунед');
  process.exit(1);
}

// Санҷиши ЯГОНАГӢ пеш аз навиштан — доми №2-и сарлавҳа.
const dupTr = LETTERS.map(l => l[3]).filter((v, i, a) => a.indexOf(v) !== i);
const dupLo = LETTERS.map(l => l[1]).filter((v, i, a) => a.indexOf(v) !== i);
const dupUp = LETTERS.map(l => l[0]).filter((v, i, a) => a.indexOf(v) !== i);
if (dupTr.length || dupLo.length || dupUp.length) {
  console.error('✗ такрор ёфт шуд — машқ мешиканад:', { dupTr, dupLo, dupUp });
  process.exit(1);
}

await sql.query(`DELETE FROM "AlphabetLetter" WHERE "targetLanguageId" = $1 AND "nativeLanguageId" = $2`, [ko.id, tg.id]);
await sql.query(`DELETE FROM "AlphabetRule"   WHERE "targetLanguageId" = $1 AND "nativeLanguageId" = $2`, [ko.id, tg.id]);

for (let i = 0; i < LETTERS.length; i++) {
  const [up, lo, ipa, tj, cat] = LETTERS[i];
  await sql.query(
    `INSERT INTO "AlphabetLetter"
       (id, "targetLanguageId", "nativeLanguageId", uppercase, lowercase, ipa,
        "tajikTranscription", category, "audioUrl", "order", "createdAt")
     VALUES ($1,$2,$3,$4,$5,$6,$7,$8,NULL,$9,NOW())`,
    [cuid(), ko.id, tg.id, up, lo, ipa, tj, cat, i]);
}

for (let i = 0; i < RULES.length; i++) {
  const [cat, title, body] = RULES[i];
  await sql.query(
    `INSERT INTO "AlphabetRule"
       (id, "targetLanguageId", "nativeLanguageId", category, title, body, "order", "createdAt")
     VALUES ($1,$2,$3,$4,$5,$6,$7,NOW())`,
    [cuid(), ko.id, tg.id, cat, title, body, i]);
}

