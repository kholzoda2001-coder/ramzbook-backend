import { readFileSync } from 'fs';
import { neon } from '@neondatabase/serverless';

const env = Object.fromEntries(
  readFileSync(new URL('../.env', import.meta.url), 'utf8')
    .split('\n').filter((l) => l.includes('=') && !l.trim().startsWith('#'))
    .map((l) => { const i = l.indexOf('='); return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, '')]; }),
);
const sql = neon(env.DATABASE_URL);
const DRY = process.argv.includes('--dry');

const [course] = await sql.query(`SELECT c.id FROM "Course" c
  JOIN "Language" t ON t.id=c."targetLanguageId"
  JOIN "Language" nn ON nn.id=c."nativeLanguageId"
 WHERE t.code='ar' AND nn.code='tg' AND c.level='A1'`);
const [mod] = await sql.query(`SELECT id FROM "Module" WHERE "courseId"=$1 AND "order"=3`, [course.id]);
const ls = await sql.query(
  `SELECT id, "grammarTopicId" g, "dialogueId" d FROM "Lesson" WHERE "moduleId"=$1 AND "isActive"`, [mod.id]);
const lids = ls.map((x) => x.id);
const gids = ls.map((x) => x.g).filter(Boolean);
const dids = ls.map((x) => x.d).filter(Boolean);
let n = 0;
const run = async (label, text, params) => {
  if (DRY) { console.log(`  [dry] ${label}`); n++; return; }
  const r = await sql.query(text + ' RETURNING 1 AS x', params);
  console.log(`  ${r.length ? '✓' : '·'} ${label}${r.length ? '' : '  ЁФТ НАШУД'}`);
  n += r.length;
};
// Калима метавонад дар ду дарс бошад (дарси асосӣ + машқи навиштан) —
// ҳамеша ҲАМАИ нусхаҳо навишта мешаванд, вагарна D6 мешиканад.
const setW = (field) => (w, v, label) => run(label,
  `UPDATE "Word" SET "${field}"=$2 WHERE "lessonId"=ANY($1) AND word=$3`, [lids, v, w]);
const setEmoji = setW('emoji');

