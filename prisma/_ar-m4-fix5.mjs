for (const l of ls) {
  const d = P[l.t];
  if (!d) { console.log(`  · Д${l.o} «${l.t}» — дар нақша нест`); continue; }
  if (DRY) { console.log(`  [dry] Д${l.o} «${l.t}» → «${d.title}» · ${d.q.length} савол`); continue; }
  await sql.query(
    `UPDATE "ComprehensionExercise" SET passage=$2, "passageTranslated"=$3, "titleTranslated"=$4 WHERE id=$1`,
    [l.k, d.ar, d.tg, d.title]);
  await sql.query(`DELETE FROM "ComprehensionQuestion" WHERE "exerciseId"=$1`, [l.k]);
  for (let i = 0; i < d.q.length; i++) {
    const [q, qt, opts, ci, ex] = d.q[i];
    await sql.query(
      `INSERT INTO "ComprehensionQuestion" (id,"exerciseId",question,"questionTranslated",options,"correctIndex",explanation,"order")
       VALUES (gen_random_uuid()::text,$1,$2,$3,$4::jsonb,$5,$6,$7)`,
      [l.k, q, qt, JSON.stringify(opts), ci, ex, i + 1]);
  }
  console.log(`  ✓ Д${l.o} «${l.t}» → «${d.title}» · ${d.q.length} савол`);
}

