// ⚠️ Рақамҳои арабӣ (٠–٩ = U+0660–0669) МИЁНИ ҳамон диапазони Unicode-и
// ҳаракатанд. Ифодаи содда «[ً-ٰ]» онҳоро низ мебурид ва «أربعة ٤» → «أربعة»
// мешуд — санҷиш маҳз ҳаминро дошт.
const strip = s => s.replace(/[ً-ٰٟؐ-ؚۖ-ۭ]/g, '');
// Ҳамсадоҳои арабӣ → ҳарфи тоҷикии хониш. Танҳо барои ХУДСАНҶӢ, на барои
// намоиш: садонокҳо ин ҷо ҳисоб намешаванд.
const CONS = {
  'ب': 'б', 'ت': 'т', 'ث': 'с', 'ج': 'ҷ', 'ح': 'ҳ', 'خ': 'х', 'د': 'д', 'ذ': 'з',
  'ر': 'р', 'ز': 'з', 'س': 'с', 'ش': 'ш', 'ص': 'с', 'ض': 'з', 'ط': 'т', 'ظ': 'з',
  'ع': 'ъ', 'غ': 'ғ', 'ف': 'ф', 'ق': 'қ', 'ك': 'к', 'ل': 'л', 'م': 'м', 'ن': 'н',
  'ه': 'ҳ', 'و': 'в', 'ي': 'й', 'ة': 'т', 'ء': '', 'أ': '', 'إ': '', 'آ': '', 'ا': '', 'ى': '',
};
const skel = s => [...strip(s).replace(/^ال/, '')].map(ch => CONS[ch] ?? '').join('').replace(/[вй]/g, '');
// Хониши тоҷикӣ → ҳамон устухонбандӣ (садонокҳо ва дефис партофта мешаванд).
const VOW = new Set([...'аиуоэыеёюяъ-  ']);
const skelTj = s => [...s.toLowerCase().replace(/^а[лрстзшнд]-?/, '').replace(/[\s\-]/g, '')]
  .filter(ch => !'аиуоэыеёюявй'.includes(ch)).join('');

// ── Санҷиш ──────────────────────────────────────────────────────────────────
const rows = await q(`SELECT DISTINCT w.word, w."ipaTajik" FROM "Word" w
  JOIN "Lesson" l ON w."lessonId"=l.id JOIN "Module" m ON l."moduleId"=m.id
  WHERE m."courseId"='${COURSE}' AND m."isActive" AND l."isActive"
    AND w.word !~ '[ً-ْٰ]'`);
const byWord = new Map(rows.map(r => [r.word, r.ipaTajik ?? '']));

const problems = [];
let ready = 0;
for (const [plain, marked] of Object.entries(H)) {
  if (!byWord.has(plain)) { problems.push(`«${plain}»: чунин калимаи бе ҳаракат дар курс нест (шояд аллакай ислоҳ шудааст)`); continue; }
  if (strip(marked) !== plain) {
    problems.push(`«${plain}» → «${marked}»: ҳарфҳо мувофиқ нестанд (бе ҳаракат «${strip(marked)}» мешавад)`);
    continue;
  }
  // Устухонбандии ҳамсадоҳо бояд ба хониши тоҷикӣ монанд бошад.
  const a = skel(marked).replace(/ъ/g, '');
  const b = skelTj(byWord.get(plain)).replace(/ъ/g, '');
  const near = a === b || a.includes(b) || b.includes(a) || Math.abs(a.length - b.length) <= 2;
  if (!near) problems.push(`«${plain}» → «${marked}»: хониш «${byWord.get(plain)}» бо ҳарфҳо мувофиқ нест (${a} ≠ ${b})`);
  ready++;
}
const missing = [...byWord.keys()].filter(w => !H[w]);
console.log(`дар ҷадвал: ${Object.keys(H).length} · тайёр: ${ready} · дар курс монда: ${missing.length}`);
if (missing.length) console.log('  ҳанӯз бе ҳаракат: ' + missing.slice(0, 20).join(' · '));
if (problems.length) { console.log(`\n${problems.length} мушкил:`); for (const p of problems) console.log(`  • ${p}`); }
else console.log('✓ ҳар шакли нав ҳамон ҳарфҳоро дорад ва ба хониш мувофиқ аст.');

if (CHECK) process.exit(problems.length ? 1 : 0);
if (problems.some(p => p.includes('мувофиқ нестанд'))) { console.log('\nНавишта НАШУД.'); process.exit(1); }

