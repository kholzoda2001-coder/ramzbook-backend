// Санҷиши муҳаррики талаффуз. Интизориҳо аз ҚОИДАҲОИ МАВҶУДИ AlphabetRule-и
// русӣ гирифта шудаанд — яъне корти калима бояд маҳз ҳамонро гӯяд, ки экрани
// Алифбо мегӯяд. Агар ин ҷо сурх шавад, ду ҷои барнома ба ҳам мухолифанд.
//
//   node prisma/_ru-phonetics-test.mjs
import { respellPhrase } from './_ru-phonetics.mjs';
import { S, S_EXTRA } from './_ru-stress-lexicon.mjs';

// Луғати луғатӣ + чанд иловаи маҳз барои санҷиш (S онҳоро надорад).
const stressOf = (bare) => S[bare] ?? S_EXTRA[bare] ?? null;

// [ибора, интизор, аз кадом қоида]
const CASES = [
  ['Москва',        'масква́',        '#8 о-и безада → а'],
  ['хорошо',        'харашо́',        '#8 (мисоли худи қоида)'],
  ['молоко',        'малако́',        '#8 (мисоли худи қоида)'],
  ['окно',          'акно́',          '#8 (мисоли худи қоида)'],
  ['сестра',        'систра́',        '#9 е-и безада → и'],
  ['друг',          'друк',           '#12 беҷарангшавии охир'],
  ['город',         'го́рат',         '#12 + #8'],
  ['его',           'ево́',           '#15 -его → -ево (override)'],
  ['сегодня',       'сево́дня',       '#15 (override)'],
  ['что',           'што',            '#18 истисно (override)'],
  ['здравствуйте',  'здра́ствуйти',   '#18 «в» хонда намешавад (override)'],
  ['спасибо',       'спаси́ба',       '#8'],
  ['привет',        'приве́т',        'зада танҳо'],
  ['пока',          'пака́',          '#8'],
  ['зовут',         'заву́т',         '#8'],
  ['извините',      'извини́ти',      '#9 е-и охири безада → и'],
  ['работа',        'рабо́та',        'зада танҳо'],
  ['язык',          'йизы́к',         '#6 + #9 (ислоҳи хатои қоидаи #9)'],
  ['До свидания',   'до свида́нийа',  'я-и охири безада → [ə] ≈ «а», на «и»'],
  ['Доброе утро',   'до́брайа у́тра',  'е-и охири безада → [ə] ≈ «а»'],
  ['Не за что',     'не́ за шта',     'ибораи яквоҳида (PHRASE_OVERRIDE)'],
  ['жить',          'жыть',           '#16 ж/ш/ц ҳамеша сахт'],
  ['из',            'ис',             '#12 беҷарангшавӣ дар калимаи якҳиҷогӣ'],
  ['имя',           'и́ма',           'я-и охири безада баъди ҲАМСАДО → [ə]'],
  ['это',           'э́та',           'о-и охири безада → а'],
  ['Россия',        'расси́йа',       'я-и охир баъди САДОНОК → «йа» + #8 о-и безада'],
  ['мужчина',       'мужчи́на',       'зада аз S_EXTRA'],
];

let pass = 0, fail = 0;
console.log('\n  ибора            интизор          натиҷа           қоида');
console.log('  ' + '─'.repeat(74));
for (const [inp, want, rule] of CASES) {
  const got = respellPhrase(inp, stressOf).text;
  const ok = got === want;
  ok ? pass++ : fail++;
  console.log(`  ${ok ? '✓' : '✗'} ${inp.padEnd(15)} ${want.padEnd(16)} ${String(got).padEnd(16)} ${rule}`);
}

// Калимаҳое ки бояд ХОЛӢ монанд (талаффуз = навишт, ҳеҷ чиз намеомӯзонад).
console.log('\n  Бояд ХОЛӢ монанд (талаффуз = навишт):');
for (const w of ['да', 'нет', 'кто', 'мой', 'три']) {
  const r = respellPhrase(w, stressOf);
  const ok = r.text === null;
  ok ? pass++ : fail++;
  console.log(`  ${ok ? '✓' : '✗'} ${w.padEnd(15)} → ${r.text ?? '(холӣ)'}`);
}

// Зада номаълум → бояд холӣ монад, НА тахмин.
console.log('\n  Задаи номаълум → бояд холӣ монад (на тахмин):');
{
  const r = respellPhrase('абракадабра', () => null);
  const ok = r.text === null && r.unknown === 'абракадабра';
  ok ? pass++ : fail++;
  console.log(`  ${ok ? '✓' : '✗'} абракадабра     → text=${r.text} unknown=${r.unknown}`);
}

console.log(`\n  ${pass} гузашт · ${fail} афтод\n`);
process.exit(fail ? 1 : 0);
