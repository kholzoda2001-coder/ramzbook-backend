// M5 #5 — ғафс кардани сарлавҳаи мавҷуда (ҳисоби ҷудогона).
{
  const idx = T.findIndex((x) => x.t === 'T3');
  const r = await sql`SELECT explanation ex FROM "GrammarTopic" WHERE id=${T[idx].id}`;
  const cur = r[0]?.ex ?? '';
  T[idx].before = cur;
  T[idx].after = cur.replace(/⚡ Фарқ аз тоҷикӣ:/u, '⚡ **Фарқ аз тоҷикӣ:**');
  if (T[idx].after === cur) T[idx].before = T[idx].after; // аллакай ғафс
}

for (const x of T) {
  const rows = await sql`
    SELECT ${sql.unsafe(`"${x.col}"`)} AS v FROM ${sql.unsafe(`"${x.table}"`)} WHERE id=${x.id}`;
  if (rows.length === 0) { drift.push(x); console.log(`  ❌ [${x.t}] ${x.label} — сатр нест`); continue; }
  const cur = rows[0].v;
  if (cur === x.after) { already++; console.log(`  ✓ [${x.t}] ${x.label} — аллакай тоза`); continue; }
  const ok = x.before === null ? isBlank(cur) : cur === x.before;
  if (!ok) {
    drift.push(x);
    console.log(`  ⚠️  [${x.t}] ${x.label} — ҲОЛАТИ ГАЙРИЧАШМДОШТ, даст нарасонд`);
    console.log(`        интизор: ${x.before === null ? '(холӣ)' : JSON.stringify(String(x.before).slice(0, 90))}`);
    console.log(`        ҷорӣ   : ${JSON.stringify(String(cur).slice(0, 90))}`);
    continue;
  }
  console.log(`  → [${x.t}] ${x.label}`);
  if (APPLY) {
    await sql`UPDATE ${sql.unsafe(`"${x.table}"`)}
              SET ${sql.unsafe(`"${x.col}"`)}=${x.after} WHERE id=${x.id}`;
  }
  changed++;
}

