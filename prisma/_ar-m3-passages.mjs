// ⚠️ Тағйири ном ПЕШ аз ҳалқаи DATA иҷро мешавад, пас дар DATA калиди НАВ.
// Имтиҳон «Оилаи ман» ном дошт — ин номи МАТН аст, на номи имтиҳон.
const RENAME = { 'Оилаи ман': 'Имтиҳони ниҳоӣ' };
for (const [from, to] of Object.entries(RENAME)) {
  if (DRY) { console.log(`[dry] унвон «${from}» → «${to}»`); continue; }
  const r = await sql.query(
    `UPDATE "ComprehensionExercise" SET "titleTranslated"=$2 WHERE id=ANY($1) AND "titleTranslated"=$3 RETURNING id`,
    [compIds, to, from]);
  console.log(`${r.length ? '✓' : '·'} унвон «${from}» → «${to}»`);
}

for (const [title, d] of Object.entries(DATA)) {
  const [ex] = await sql.query(
    `SELECT id FROM "ComprehensionExercise" WHERE id=ANY($1) AND "titleTranslated"=$2`, [compIds, title]);
  if (!ex) { console.log(`⚠ «${title}» ёфт нашуд`); continue; }
  if (DRY) { console.log(`[dry] «${title}»: матн + ${d.qs.length} савол`); continue; }
  await sql.query(`UPDATE "ComprehensionExercise" SET passage=$2, "passageTranslated"=$3 WHERE id=$1`,
    [ex.id, d.p, d.t]);
  await sql.query(`DELETE FROM "ComprehensionQuestion" WHERE "exerciseId"=$1`, [ex.id]);
  for (let i = 0; i < d.qs.length; i++) {
    const q = d.qs[i];
    await sql.query(
      `INSERT INTO "ComprehensionQuestion" (id,"exerciseId",question,"questionTranslated",options,"correctIndex","order")
       VALUES (gen_random_uuid()::text,$1,$2,$3,$4::jsonb,$5,$6)`,
      [ex.id, q.q, q.t, JSON.stringify(q.o), q.c, i + 1]);
  }
  console.log(`✓ «${title}»: матн + ${d.qs.length} савол`);
}

