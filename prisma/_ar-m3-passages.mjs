const rows = await sql.query(`SELECT id, "order" FROM "DialogueLine" WHERE "dialogueId"=$1`, [dlgId]);
for (const [o, text, tr] of DLG) {
  const row = rows.find((r) => r.order === o);
  if (!row) { console.log(`⚠ сатри ${o} нест`); continue; }
  if (DRY) { console.log(`[dry] муколама сатри ${o}`); continue; }
  await sql.query(`UPDATE "DialogueLine" SET text=$2, translation=$3 WHERE id=$1`, [row.id, text, tr]);
  console.log(`✓ муколама сатри ${o}`);
}
