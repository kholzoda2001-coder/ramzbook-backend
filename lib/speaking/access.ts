/**
 * Кӣ кадом дарси ГУФТОРРО кушода метавонад.
 *
 * ── Чаро ин файл ҳаст ──────────────────────────────────────────────────────
 * То ин дам тамоми бахши гуфтор РОЙГОН буд: `SpeakingCategory.isPremium` дар
 * схема вуҷуд дошт, вале ягон роут онро намехонд. Қарори соҳиби маҳсулот
 * (2026-09-06): гуфтор бахши ПРЕМИУМ мешавад, ба ҷуз ЯК дарси намоишӣ.
 *
 * Сабаб равшан аст: ҳар кӯшиши гуфтор ба Azure меравад ва ПУЛ мехӯрад. Ин
 * ягона қисми барнома аст, ки хароҷоти воқеии ҳар корбарро дорад — пас маҳз
 * он бояд обунаро сафед кунад.
 *
 * ── Қоида ──────────────────────────────────────────────────────────────────
 *   1. Премиум → ҳама чиз.
 *   2. Вагарна: аввалин [FREE_SPEAKING_LESSONS] дарси занҷир — яъне
 *      дарси 1-и боби 1. Ҳамин ва бас.
 *   3. + ҳар дарсе, ки корбар АЛЛАКАЙ гузаштааст.
 *
 * Қоидаи 3 қасдан аст. Дар лаҳзаи ҷорӣ шудани пейвол корбароне ҳастанд, ки
 * гуфторро ройгон гузаштаанд. Аз онҳо гирифтани чизи аллакай доштаашон —
 * маҳз ҳамон чизест, ки шикоят ва баҳои 1-ситора меорад. Онҳо метавонанд
 * дарсҳои гузаштаро такрор кунанд; барои дарси НАВ обуна лозим аст.
 *
 * ⚠️ Тартиб МУҲИМ аст: занҷир аз рӯи `SpeakingCategory.order`, баъд
 * `SpeakingLesson.order` ҳисоб мешавад — ҳамон тартибе, ки роути дарс
 * барои интихоби «дарси навбатӣ» истифода мебарад. Агар ин ду ҷо аз ҳам
 * фарқ кунанд, корбар дарсеро мебинад, ки кушода наметавонад.
 */

/**
 * Чанд дарси гуфтор барои корбари БЕ обуна кушода аст.
 *
 * `1` = танҳо дарси якуми боби якум дар тамоми бахш.
 *
 * ⚠️ Ин рақам ЯГОНА манбаи ҳақиқат аст. Агар пейвол рӯзе «2 дарс ройгон»
 * ваъда диҳад, ин ҷо иваз кунед — на дар матни пейвол.
 */
export const FREE_SPEAKING_LESSONS = 1;

/**
 * Гейт УМУМАН фаъол аст?
 *
 * 🟢 `true` = ФАЪОЛ (2026-09-07). Қарори соҳиби маҳсулот.
 *
 * ── Он чи ин маънӣ дорад ───────────────────────────────────────────────────
 * Корбари бе обуна танҳо [FREE_SPEAKING_LESSONS] дарси аввалро мекушояд;
 * барои боқимонда `403` мегирад ва барномаи НАВ ба ҷои он пейволро нишон
 * медиҳад.
 *
 * ⚠️ ХАВФИ ДОНИСТАШУДА: барномае, ки дар Google Play аст, ҲАНӮЗ КӮҲНА аст
 * ва `403`-ро намефаҳмад — корбари ройгон дар он ба ҷои пешниҳоди харид
 * экрани «Хатогӣ рӯй дод» мебинад. Ин то нашри APK-и нав дар Play идома
 * меёбад ва ҚАСДАН қабул шудааст, то гейт ҳозир санҷида шавад.
 *
 * ➡️ Роҳи бозгашт ЯК сатр аст: `false` + деплой. Ҳеҷ маълумот тағйир
 *    намеёбад — гейт танҳо хондан аст.
 *
 * ⚠️ Ин парчам ҚАСДАН аз `FREE_SPEAKING_LESSONS` ҶУДОст. Роҳи дигар —
 * рақамро ба 999 бардоштан — маънои он константаро вайрон мекард ва
 * матни пейвол «999 дарс ройгон» мегуфт.
 */
export const SPEAKING_GATE_ENABLED = true;

/** Он майдонҳое, ки қоидаи дастрасӣ лозим дорад. */
export type AccessLesson = { id: string };
export type AccessChapter = { lessons: AccessLesson[] };

export interface AccessInput {
  /** Бобҳо бо тартиби `order`, дарсҳо низ бо тартиби `order`. */
  chapters: AccessChapter[];
  /** `SpeakingProgress` — дарсҳои аллакай гузашта. */
  completedIds?: Iterable<string>;
  isPremium: boolean;
}

/**
 * Маҷмӯи id-и дарсҳое, ки ин корбар кушода метавонад.
 *
 * Функсияи СОФ — бе Prisma, бе I/O. Ҳам роути дарс ва ҳам роути рӯйхати
 * бобҳо маҳз ҳаминро даъват мекунанд, то экран ва сервер ҳеҷ гоҳ ду
 * ҷавоби гуногун надиҳанд.
 */
export function unlockedSpeakingLessonIds({
  chapters,
  completedIds,
  isPremium,
}: AccessInput): Set<string> {
  const all = chapters.flatMap((c) => c.lessons.map((l) => l.id));
  if (!SPEAKING_GATE_ENABLED || isPremium) return new Set(all);

  const open = new Set(all.slice(0, FREE_SPEAKING_LESSONS));
  // ⚠️ `Array.from`, на `for…of`: `tsconfig` ҳадафи поёнтар аз ES2015 дорад
  // ва гардиши мустақими `Set`/`Iterable` дар билд хато медиҳад.
  Array.from(completedIds ?? []).forEach((id) => {
    // Танҳо дарсҳои ҲАМИН занҷир — сатри бегонаи прогресс чизе намекушояд.
    if (all.indexOf(id) !== -1) open.add(id);
  });
  return open;
}

/** Ҷавоби ягонаи «ин дарс баста аст». */
export const SPEAKING_LOCKED = {
  error: 'Premium required',
  locked: true,
} as const;
