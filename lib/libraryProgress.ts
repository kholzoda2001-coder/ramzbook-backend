/**
 * Ду қарори ҷои хониш дар Китобхона — ҷудо аз роут, то тестшаванда бошанд.
 *
 * Талаби корбар: «дар ягон ҳолат барнома прогресси хонандаро дар китобҳо нест
 * накунад» — на ҳангоми насби нав, на ҳангоми баромадан ва вуруди дубора, на
 * ҳангоми хондан аз ду дастгоҳ. Ҳамин ду функсия маҳз ҳамонро кафолат медиҳанд.
 */

/**
 * Соати МИЗОҶро қабул мекунем, вале аз ОЯНДА не.
 *
 * Чаро: як телефони бо соати нодуруст метавонад `lastReadAt`-и соли оянда
 * фиристад — он гоҳ сатр то абад «навтарин» мешуд ва ҳеҷ дастгоҳи дигар,
 * ҳатто худи ҳамон корбар, дигар онро нав карда наметавонист.
 */
export function normaliseClientTime(claimed: Date | null | undefined, now: Date): Date {
  if (!claimed || Number.isNaN(+claimed) || claimed > now) return now;
  return claimed;
}

/**
 * Оё ин навсозӣ кӯҳна аст ва бояд рад шавад?
 *
 * Чаро: телефоне, ки муддате офлайн буд, ҳангоми пайваст шудан ҷои КӮҲНАи
 * худро мефиристад. Бе ин санҷиш он ҷои НАВи дастгоҳи дигарро мепӯшонд ва
 * хонанда бобҳои хондаашро аз даст медод.
 */
export function isStaleRead(incoming: Date, stored: Date | null | undefined): boolean {
  if (!stored) return false;
  return incoming < stored;
}
