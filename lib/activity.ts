import { prisma } from './prisma';

/**
 * lib/activity.ts — «ин хонанда ҲОЗИР кор кард».
 *
 * Ягона ҷое, ки фаъолияти таълимиро сабт мекунад. ҲАР амали воқеии таълим бояд
 * инро даъват кунад: хатми дарс (бори аввал Ё такрор), муколамаи speaking,
 * ҳар корти навбати такрор (SRS).
 *
 * ЧАРО ҷудо аз `awardXp`: XP танҳо як бор дода мешавад (`firstCompletion`), то
 * касе бо такрори дарс XP наканад. Вале «хондан» ва «XP гирифтан» ду чизи
 * гуногунанд. То ин ҷудокунӣ набуд, огоҳиҳо хонандаи фаъолро НАМЕДИДАНД:
 *   • такрори дарси хатмшуда → сервер чизе намедонист;
 *   • такрори муколамаи speaking → ҳамин тавр;
 *   • тамоми навбати такрор (SRS) → тамоман сабт намешуд.
 * Натиҷа: касе, ки маҳз ҳозир ним соат такрор мекард, соати 19:00 паёми
 * «имрӯз ҳанӯз нахондаӣ» мегирифт — маҳз он чизе, ки push-ро ба спам табдил
 * медиҳад.
 *
 * `lastActiveAt` низ нав мешавад, то занҷири win-back (3/7/14/30 рӯз) ҳам
 * хонандаи такроркунандаро «ғайрифаъол» ҳисоб накунад.
 */
export async function markStudied(userId: string, now = new Date()): Promise<void> {
  try {
    await prisma.user.update({
      where: { id: userId },
      data: { lastStudyAt: now, lastActiveAt: now },
    });
  } catch (_) {
    // Сабти фаъолият ҳеҷ гоҳ набояд худи дарсро вайрон кунад — бадтарин оқибат
    // як огоҳии барзиёд аст, на хатои корбар.
  }
}
