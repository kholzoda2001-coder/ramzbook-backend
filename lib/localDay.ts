/**
 * «Рӯз» аз нигоҳи ХОНАНДА — на аз нигоҳи сервер.
 *
 * Ин файл аз `lib/xp.ts` ҷудо карда шуд, то ҳисоби рӯзи маҳаллӣ ЯГОНА бошад.
 * Дар лоиҳа аллакай як нусхаи дуюми мантиқи силсила ҳаст
 * (`lib/streak.ts`, ки `UTC+5`-ро сахт мехонад ва ҳеҷ кас онро даъват
 * намекунад) — маҳз чунин нусхабардорӣ буд, ки рафтори силсиларо дар ду ҷо
 * гуногун кард. Ҳар коде, ки бояд донад «имрӯз»-и корбар кай сар мешавад,
 * бояд ҲАМИН ҶО-ро истифода барад.
 */

/**
 * Минтақаи вақти пешфарз, вақте дастгоҳи корбар онро ҳанӯз нагуфтааст:
 * Душанбе (UTC+5). Аксарияти мутлақи хонандагон он ҷоянд, пас ин тахмин
 * барои онҳо АЙНАН дуруст аст, на тахмини бетараф.
 */
export const DEFAULT_TZ_OFFSET_MIN = 300;

/**
 * Калиди `YYYY-MM-DD` дар минтақаи вақти худи корбар.
 *
 * ЧАРО ин лозим шуд: силсила бо рӯзи UTC ҳисоб мешуд, яъне барои хонандаи
 * тоҷик рӯз соати **05:00 бомдод** иваз мешуд, на дар нимишаб. Ду оқибати
 * воқеӣ дошт:
 *   • касе, ки соати 01:00-и шаб дарс мехонд, онро ба ДИРӮЗ навишта мешуд —
 *     яъне «имрӯз» ҳанӯз холӣ буд ва силсилааш метавонист бишканад;
 *   • огоҳии «то нимишаб фалон вақт монд» бо ҳақиқат мувофиқ намеомад.
 * Акнун нимишаби корбар ҳам дар матн, ҳам дар муҳаррик ҳамон як лаҳза аст.
 */
export function localDayKey(d: Date, tzOffsetMin: number): string {
  return new Date(d.getTime() + tzOffsetMin * 60_000).toISOString().split('T')[0];
}

/**
 * Ҳамон рӯз, вале ҳамчун РАҚАМ — то ки фарқи ду санаро ҳисоб кардан мумкин
 * бошад («чанд рӯзи пурра холӣ гузашт?»). Калиди сатрӣ инро дода наметавонад.
 */
export function localDayIndex(d: Date, tzOffsetMin: number): number {
  return Math.floor((d.getTime() + tzOffsetMin * 60_000) / 86_400_000);
}
